import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'

import { CENTRO, NORTE, buildMovement } from '../../test-utils/inventoryMovements'

import { MovementDetail } from './MovementDetail'

function renderDetail(overrides = {}, viewedBranchId?: string) {
  const onClose = vi.fn()
  const user = userEvent.setup()
  const movement = buildMovement(overrides)
  render(<MovementDetail movement={movement} viewedBranchId={viewedBranchId} onClose={onClose} />)
  return { user, onClose }
}

describe('MovementDetail', () => {
  it('shows every row of the movement', () => {
    renderDetail()

    expect(screen.getByText('Tipo')).toBeInTheDocument()
    expect(screen.getByText('Fecha y hora')).toBeInTheDocument()
    expect(screen.getByText('Producto')).toBeInTheDocument()
    expect(screen.getByText('Cantidad')).toBeInTheDocument()
    expect(screen.getByText('Lote')).toBeInTheDocument()
    expect(screen.getByText('Sede')).toBeInTheDocument()
    expect(screen.getByText('Registró')).toBeInTheDocument()

    expect(screen.getByText('Whey Protein 2 lb · WHEY-2LB')).toBeInTheDocument()
    expect(screen.getByText('−3 und')).toBeInTheDocument()
    expect(screen.getByText('Centro')).toBeInTheDocument()
    expect(screen.getByText('Laura Pérez')).toBeInTheDocument()
  })

  it('describes the lot with its expiration date and state', () => {
    renderDetail({ expirationDate: '2027-01-31' })

    expect(
      screen.getByText(/Vence 31 ene 2027 \((vigente|por vencer|vencido)\)/i),
    ).toBeInTheDocument()
  })

  it('falls back when the movement has no lot', () => {
    renderDetail({ expirationDate: null })

    expect(screen.getByText('Sin lote registrado')).toBeInTheDocument()
  })

  it('names the origin and destination for a transfer', () => {
    renderDetail({
      movementType: 'TRANSFER',
      originBranch: { id: CENTRO.id, name: CENTRO.name },
      branch: { id: NORTE.id, name: NORTE.name },
    })

    expect(screen.getByText('Origen → destino')).toBeInTheDocument()
    expect(screen.getByText('Centro → Norte')).toBeInTheDocument()
  })

  it('labels the note as the reason for an adjustment and as an observation otherwise', () => {
    const { unmount } = render(
      <MovementDetail
        movement={buildMovement({ movementType: 'ADJUSTMENT_EXIT', observation: 'Conteo físico' })}
        onClose={vi.fn()}
      />,
    )
    expect(screen.getByText('Razón del ajuste')).toBeInTheDocument()
    expect(screen.getByText('Conteo físico')).toBeInTheDocument()
    unmount()

    render(
      <MovementDetail
        movement={buildMovement({ movementType: 'EXIT', observation: 'Empaque roto' })}
        onClose={vi.fn()}
      />,
    )
    expect(screen.getByText('Observación')).toBeInTheDocument()
    expect(screen.getByText('Empaque roto')).toBeInTheDocument()
  })

  it('falls back when there is no observation', () => {
    renderDetail({ observation: null })

    expect(screen.getByText('Sin observación.')).toBeInTheDocument()
  })

  it('falls back when the user has no name', () => {
    renderDetail({ user: { id: 'user-x', fullName: '' } })

    expect(screen.getByText('Usuario sin nombre')).toBeInTheDocument()
  })

  it('explains a movement generated by a sale', () => {
    renderDetail({ saleId: 'sale-1' })

    expect(
      screen.getByText('Movimiento generado automáticamente por una venta del punto de venta.'),
    ).toBeInTheDocument()
  })

  it('explains a movement generated by a purchase receipt', () => {
    renderDetail({ purchaseId: 'purchase-1' })

    expect(
      screen.getByText('Movimiento generado automáticamente por la recepción de una compra.'),
    ).toBeInTheDocument()
  })

  it('does not show the origin note when the movement is manual', () => {
    renderDetail()

    expect(screen.queryByText(/Movimiento generado automáticamente/)).not.toBeInTheDocument()
  })

  it('calls onClose when the close button is clicked', async () => {
    const { user, onClose } = renderDetail()

    await user.click(screen.getByRole('button', { name: 'Cerrar' }))

    expect(onClose).toHaveBeenCalledTimes(1)
  })
})
